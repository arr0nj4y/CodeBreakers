const { chromium } = require('playwright');
const path = require('path');
const assert = require('node:assert/strict');
const url = 'file:///' + path.resolve('codebreakers_tripleA_cinematic_polish_v3.html').split(path.sep).join('/');
(async () => {
 const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--allow-file-access-from-files'] });
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
 const errors = [], requests = [];
 page.on('pageerror', e => errors.push(e.message));
 page.on('request', r => { if (!/^(data|file|blob):/.test(r.url())) requests.push(r.url()); });
 await page.goto(url);
 await page.waitForTimeout(2000);
 await page.screenshot({ path: '.qa/menu.png' });
 if (process.argv.includes('--verify')) {
  assert.equal(await page.locator('#menuScreen').isVisible(), true, 'Opens on the command deck');
  assert.equal(await page.locator('#warTable').getAttribute('data-renderer'), 'webgl', 'War table renders in WebGL');
  assert.equal(await page.locator('#tableMotion').getAttribute('aria-pressed'), 'false');
  await page.locator('#tableMotion').click();
  assert.equal(await page.locator('#tableMotion').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#warTable').getAttribute('data-paused'), 'true');
  await page.locator('#tableMotion').click();
  assert.equal(await page.evaluate(() => window.HelmAudio.playing), true, 'Music starts on the first interaction');
  await page.locator('.pin[data-world="2"]').click(); await page.waitForTimeout(900);
  assert.equal(await page.locator('#sectorName').textContent(), 'Encryption Vault');
  assert.equal(await page.locator('.pin[data-world="2"]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#sectorMissions .mrow').count(), 3, 'Each world lists its three missions');
  await page.locator('.pin[data-world="0"]').click(); await page.waitForTimeout(900);
  await page.locator('#sectorMissions .mrow').first().click();
  await page.locator('#deployMission').click();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('#board').isVisible(), true);
  assert.equal(await page.locator('#board .tile').count(), 49);
  assert.equal(await page.locator('#board .tile.agent').getAttribute('data-piece'), 'agent', 'Board uses the Blender agent sprite');
  assert.equal(await page.evaluate(() => window.HelmAudio.target), 'mission', 'Mission music mood');
  await page.locator('#options button').first().click();
  await page.locator('#codeEditor').fill('moveRight();');
  await page.locator('#compileCode').click();
  assert.equal(await page.locator('#qlen').textContent(), '1');
  await page.locator('#learnStep').click();
  await page.waitForTimeout(800);
  assert.match(await page.locator('#moves').textContent(), /Steps: 1/);
  const pictographs = await page.evaluate(() => (document.querySelector('.app').innerText.replace(document.getElementById('board').innerText,'').match(/\p{Extended_Pictographic}/gu) || []).join(''));
  assert.equal(pictographs, '', 'No emoji stand in for icons on the mission screen');
  await page.screenshot({ path: '.qa/game.png', fullPage: true });
  await page.locator('#toMenu').click();
  assert.equal(await page.locator('#deckXp').textContent(), '20', 'Checkpoint XP is credited');
  await page.reload(); await page.waitForTimeout(1500);
  assert.equal(await page.locator('#deckXp').textContent(), '20', 'Earned progress survives reload');
  assert.deepEqual(requests, [], 'No network requests');
  assert.deepEqual(errors, [], 'No runtime exceptions');
  console.log('PASS: war table, motion control, world selection, deployment, sprites, code compilation, movement, checkpoint XP, saved progress, music, offline.');
 }
 await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
