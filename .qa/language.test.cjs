const assert=require('node:assert/strict');
const fs=require('fs');
assert.ok(fs.existsSync('.qa/learning-language.js'),'Source-aware teaching compiler must exist');
const {compile}=require('./learning-language.js');
const start={x:0,y:0,key:false,switchOn:false,fragments:0,unlocked:true,visited:[]};
const map=['S.K....','.......','.......','.......','.......','.......','......E'];
let r=compile('// example\nrepeat(2) {\n moveRight();\n}\nif(hasKey()) { moveDown(); } else { moveLeft(); }',map,start);
assert.deepEqual(r.moves,['R','R','D']);assert.deepEqual(r.trace.map(t=>t.line),[3,3,5]);
assert.deepEqual(r.trace.slice(0,2).map(t=>t.loops[0].iteration),[1,2]);
assert.equal(r.trace[2].conditions[0].result,true);assert.equal(r.features.loop,true);assert.equal(r.features.condition,true);
r=compile('repeat(2) { if(pathClear("R")) { moveRight(); } else { moveDown(); } }',['S.#....',...map.slice(1)],start);
assert.deepEqual(r.moves,['R','D']);assert.equal(r.trace[1].conditions[0].result,false);
assert.throws(()=>compile('repeat(80) { moveRight(2); }',map,start),/80/);
assert.throws(()=>compile('fetch("https://example.com");',map,start),/Unknown/);
assert.throws(()=>compile('moveRight(1.5);',map,start),/line 1/i);
assert.throws(()=>compile('repeat(2) { moveRight();',map,start),/closing|Expected/i);
assert.deepEqual(compile('repeat(0){ moveRight(); } moveDown();',map,start).moves,['D']);
assert.deepEqual(compile('for(let i=0;i<=2;i++){moveRight();}',map,start).moves,['R','R','R']);
assert.equal(start.x,0,'Compilation does not mutate game state');
console.log('PASS: source lines, loop iterations, state-dependent branches, safety limits, syntax errors and immutability.');
